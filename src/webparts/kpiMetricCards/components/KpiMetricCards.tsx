const fetchListItems = async (
  props: IKpiMetricCardsProps,
  configuration: IListConfiguration
): Promise<IListFetchResult> => {
  try {
    const sp =
      getSP(
        props.context
      );

    const rawItems:
      IRawSharePointItem[] =
        await sp.web.lists
          .getByTitle(
            configuration.title
          )
          .items
          .select(
            'Id',
            configuration
              .percentageInternalName
          )
          .top(
            5000
          )() as IRawSharePointItem[];

    const items:
      IResponseItem[] =
        rawItems.map(
          (
            item:
              IRawSharePointItem
          ): IResponseItem => {
            return {
              id:
                typeof item.Id === 'number'
                  ? item.Id
                  : undefined,

              sharePointScore:
                item[
                  configuration
                    .percentageInternalName
                ]
            };
          }
        );

    return {
      listTitle:
        configuration.title,

      items,

      succeeded:
        true
    };
  } catch (error: unknown) {
    const errorMessage:
      string =
        getErrorMessage(
          error
        );

    console.error(
      '[Supplier ESG KPI] Unable to retrieve list items.',
      {
        listTitle:
          configuration.title,

        error:
          errorMessage
      }
    );

    return {
      listTitle:
        configuration.title,

      items:
        [],

      succeeded:
        false,

      errorMessage
    };
  }
};

const calculateKpiData = (
  results:
    readonly IListFetchResult[],

  configurations:
    readonly IListConfiguration[]
): IKpiData => {
  const calculatedData:
    IKpiData = {
      total:
        0,

      pending:
        0,

      approved:
        0,

      actionRequired:
        0,

      highRisk:
        0
    };

  results.forEach(
    (
      result:
        IListFetchResult,

      index:
        number
    ): void => {
      if (
        !result.succeeded
      ) {
        return;
      }

      const configuration:
        IListConfiguration =
          configurations[index];

      result.items.forEach(
        (
          item:
            IResponseItem
        ): void => {
          calculatedData.total += 1;

          const exactScore:
            number | undefined =
              parseExactSharePointScore(
                item.sharePointScore
              );

          /*
           * A submission with no valid SharePoint score is pending.
           */
          if (
            exactScore === undefined
          ) {
            calculatedData.pending += 1;
            return;
          }

          /*
           * Exact SharePoint score meets the qualified threshold.
           */
          if (
            exactScore >=
            configuration.qualifiedMinimum
          ) {
            calculatedData.approved += 1;
            return;
          }

          /*
           * Exact SharePoint score meets the conditional threshold.
           */
          if (
            exactScore >=
            configuration.conditionalMinimum
          ) {
            calculatedData.actionRequired += 1;
            return;
          }

          /*
           * Exact SharePoint score is below the conditional threshold.
           */
          calculatedData.highRisk += 1;
        }
      );
    }
  );

  const classifiedTotal:
    number =
      calculatedData.pending +
      calculatedData.approved +
      calculatedData.actionRequired +
      calculatedData.highRisk;

  console.info(
    '[Supplier ESG KPI validation]',
    {
      total:
        calculatedData.total,

      classified:
        classifiedTotal,

      isBalanced:
        calculatedData.total ===
        classifiedTotal,

      details:
        calculatedData
    }
  );

  return calculatedData;
};

