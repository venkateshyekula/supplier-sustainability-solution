/*
 * V9 prevents values generated by the previous normalized
 * 80%, 50%, and 20% KPI logic from being reused.
 */
const CACHE_VERSION:
  string = 'V9';

const CACHE_KEY_PREFIX:
  string =
    `SSQ_KPI_METRICS_DATA_${CACHE_VERSION}`;

const CACHE_TTL_MS:
  number =
    10 * 60 * 1000;

const getErrorMessage = (
  error: unknown
): string => {
  if (error instanceof Error) {
    return error.message;
  }

  return String(error);
};

const createCacheKeySegment = (
  value: string
): string => {
  return value
    .replace(
      /[^a-zA-Z0-9]/g,
      '_'
    )
    .substring(
      0,
      180
    );
};

const createCacheKey = (
  webUrl: string,
  configurations:
    readonly IListConfiguration[]
): string => {
  const configurationSegment:
    string =
      configurations
        .map(
          (
            configuration:
              IListConfiguration
          ): string => {
            return createCacheKeySegment(
              configuration.title
            );
          }
        )
        .join(
          '__'
        );

  return (
    `${CACHE_KEY_PREFIX}_` +
    `${createCacheKeySegment(webUrl)}_` +
    `${configurationSegment}`
  );
};

const isKpiData = (
  value: unknown
): value is IKpiData => {
  if (
    typeof value !== 'object' ||
    value === null
  ) {
    return false;
  }

  const candidate:
    Partial<IKpiData> =
      value as Partial<IKpiData>;

  return (
    typeof candidate.total === 'number' &&
    typeof candidate.pending === 'number' &&
    typeof candidate.approved === 'number' &&
    typeof candidate.actionRequired === 'number' &&
    typeof candidate.highRisk === 'number'
  );
};

const readCachedKpi = (
  cacheKey: string
): IKpiData | undefined => {
  try {
    const cachedJson:
      string | null =
        window.sessionStorage.getItem(
          cacheKey
        );

    if (!cachedJson) {
      return undefined;
    }

    const cachedValue:
      ICachedKpiData =
        JSON.parse(
          cachedJson
        ) as ICachedKpiData;

    if (
      !cachedValue ||
      typeof cachedValue.cachedAt !== 'number' ||
      !isKpiData(cachedValue.data)
    ) {
      window.sessionStorage.removeItem(
        cacheKey
      );

      return undefined;
    }

    const cacheAge:
      number =
        Date.now() -
        cachedValue.cachedAt;

    if (
      cacheAge > CACHE_TTL_MS
    ) {
      window.sessionStorage.removeItem(
        cacheKey
      );

      return undefined;
    }

    return cachedValue.data;
  } catch (error: unknown) {
    console.warn(
      '[Supplier ESG KPI] Unable to read cached KPI data.',
      error
    );

    return undefined;
  }
};

const writeCachedKpi = (
  cacheKey: string,
  data: IKpiData
): void => {
  try {
    const cachedValue:
      ICachedKpiData = {
        data,
        cachedAt:
          Date.now()
      };

    window.sessionStorage.setItem(
      cacheKey,
      JSON.stringify(
        cachedValue
      )
    );
  } catch (error: unknown) {
    console.warn(
      '[Supplier ESG KPI] Unable to cache KPI data.',
      error
    );
  }
};

/**
 * Parses the exact numeric value returned by SharePoint.
 *
 * The method removes visual formatting such as "%" and
 * decimal commas, but does not normalize, divide, multiply,
 * or otherwise change the numeric scale.
 *
 * Examples:
 * "10%"   -> 10
 * "9.99%" -> 9.99
 * "5%"    -> 5
 * "4.99%" -> 4.99
 * "2%"    -> 2
 * "1.99%" -> 1.99
 */
const parseExactSharePointScore = (
  value: unknown
): number | undefined => {
  if (
    value === null ||
    value === undefined ||
    value === ''
  ) {
    return undefined;
  }

  if (
    typeof value === 'number'
  ) {
    return (
      isFinite(value) &&
      value >= 0
    )
      ? value
      : undefined;
  }

  if (
    typeof value !== 'string'
  ) {
    return undefined;
  }

  const normalizedValue:
    string =
      value
        .replace(
          /%/g,
          ''
        )
        .replace(
          ',',
          '.'
        )
        .trim();

  if (
    !normalizedValue
  ) {
    return undefined;
  }

  const parsedValue:
    number =
      parseFloat(
        normalizedValue
      );

  if (
    isNaN(parsedValue) ||
    !isFinite(parsedValue) ||
    parsedValue < 0
  ) {
    return undefined;
  }

  return parsedValue;
};

