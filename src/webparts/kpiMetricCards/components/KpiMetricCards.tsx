export function KpiMetricCards(
  props: IKpiMetricCardsProps
): React.ReactElement {
  const [
    kpi,
    setKpi
  ] =
    useState<IKpiData>(
      EMPTY_KPI_DATA
    );

  const [
    loading,
    setLoading
  ] =
    useState<boolean>(
      true
    );

  const [
    errorMessage,
    setErrorMessage
  ] =
    useState<string>(
      ''
    );

  useEffect(
    (): (() => void) => {
      let isMounted:
        boolean =
          true;

      const loadKpiData =
        async (): Promise<void> => {
          const configurations:
            readonly IListConfiguration[] =
              getListConfigurations(
                props
              );

          const webUrl:
            string =
              props.context
                .pageContext
                .web
                .absoluteUrl;

          const cacheKey:
            string =
              createCacheKey(
                webUrl,
                configurations
              );

          const cachedData:
            IKpiData | undefined =
              readCachedKpi(
                cacheKey
              );

          if (
            cachedData &&
            isMounted
          ) {
            setKpi(
              cachedData
            );

            setLoading(
              false
            );
          } else if (
            isMounted
          ) {
            setLoading(
              true
            );
          }

          try {
            const results:
              IListFetchResult[] =
                await Promise.all(
                  configurations.map(
                    (
                      configuration:
                        IListConfiguration
                    ): Promise<IListFetchResult> => {
                      return fetchListItems(
                        props,
                        configuration
                      );
                    }
                  )
                );

            if (
              !isMounted
            ) {
              return;
            }

            const successfulResults:
              IListFetchResult[] =
                results.filter(
                  (
                    result:
                      IListFetchResult
                  ): boolean => {
                    return result.succeeded;
                  }
                );

            const failedResults:
              IListFetchResult[] =
                results.filter(
                  (
                    result:
                      IListFetchResult
                  ): boolean => {
                    return !result.succeeded;
                  }
                );

            if (
              successfulResults.length === 0
            ) {
              setKpi(
                EMPTY_KPI_DATA
              );

              setErrorMessage(
                'KPI metrics could not be loaded from ' +
                'the configured SharePoint lists.'
              );

              return;
            }

            const calculatedData:
              IKpiData =
                calculateKpiData(
                  results,
                  configurations
                );

            setKpi(
              calculatedData
            );

            writeCachedKpi(
              cacheKey,
              calculatedData
            );

            if (
              failedResults.length > 0
            ) {
              const failedTitles:
                string =
                  failedResults
                    .map(
                      (
                        result:
                          IListFetchResult
                      ): string => {
                        return result.listTitle;
                      }
                    )
                    .join(
                      ', '
                    );

              setErrorMessage(
                'Some KPI sources could not be loaded: ' +
                `${failedTitles}. Metrics shown are partial.`
              );
            } else {
              setErrorMessage(
                ''
              );
            }
          } catch (
            error:
              unknown
          ) {
            console.error(
              '[Supplier ESG KPI] Unexpected KPI loading error.',
              error
            );

            if (
              isMounted
            ) {
              setErrorMessage(
                'An unexpected error occurred while ' +
                'loading the supplier ESG KPI metrics.'
              );
            }
          } finally {
            if (
              isMounted
            ) {
              setLoading(
                false
              );
            }
          }
        };

      loadKpiData()
        .catch(
          (
            error:
              unknown
          ): void => {
            console.error(
              '[Supplier ESG KPI] Unhandled KPI loading error.',
              error
            );

            if (
              isMounted
            ) {
              setLoading(
                false
              );

              setErrorMessage(
                'An unexpected error occurred while ' +
                'loading the supplier ESG KPI metrics.'
              );
            }
          }
        );

      return (): void => {
        isMounted =
          false;
      };
    },
    [
      props.context,
      props.tier1ListTitle,
      props.tier2ListTitle,
      props.tier3ListTitle
    ]
  );

  if (
    loading
  ) {
    return (
      <div
        role="status"
        aria-live="polite"
        style={loadingStyle}
      >
        <Spinner
          size={SpinnerSize.small}
          label="Loading supplier ESG KPI metrics"
        />
      </div>
    );
  }

  return (
    <section
      style={wrapperStyle}
      aria-label="Supplier ESG KPI metrics"
    >
      {errorMessage && (
        <div
          role="alert"
          style={warningStyle}
        >
          {errorMessage}
        </div>
      )}

      <div style={containerStyle}>
        {KPI_CARDS.map(
          (
            card:
              IKpiCardConfiguration
          ): React.ReactElement => {
            return (
              <article
                key={card.key}
                style={{
                  ...cardStyle,

                  color:
                    card.color,

                  backgroundColor:
                    card.cardBackgroundColor,

                  borderColor:
                    card.borderColor
                }}
                aria-label={
                  `${card.title}: ` +
                  `${kpi[card.key].toString()}`
                }
              >
                <div
                  style={{
                    ...iconContainerStyle,

                    color:
                      card.color,

                    backgroundColor:
                      card.iconBackgroundColor
                  }}
                  aria-hidden="true"
                >
                  <Icon
                    iconName={
                      card.iconName
                    }
                    styles={{
                      root: {
                        color:
                          card.color,

                        fontSize:
                          '36px',

                        lineHeight:
                          '36px'
                      }
                    }}
                  />
                </div>

                <strong style={valueStyle}>
                  {kpi[card.key]}
                </strong>

                <div style={textContainerStyle}>
                  <h3 style={titleStyle}>
                    {card.title}
                  </h3>

                  <span style={descriptionStyle}>
                    {card.description}
                  </span>
                </div>
              </article>
            );
          }
        )}
      </div>
    </section>
  );
}

export default KpiMetricCards;